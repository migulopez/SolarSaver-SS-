/**
 * SolarCalculator.js
 * Computes solar position, irradiance, and electrical output from the external panel.
 */

export class SolarCalculator {
  constructor() {
    this.panelRatedPower = 40; // 40 Watts peak (STC: 1000 W/m² at 25°C)
    this.panelEfficiency = 0.21; // 21% Monocrystalline efficiency
  }

  /**
   * Computes Sun direction vector based on timeOfDay (0.0 to 24.0 hours)
   * 6:00 is sunrise (East, elevation 0), 12:00 is solar noon (South/Overhead), 18:00 sunset (West)
   * @param {number} timeOfDay - hours (e.g. 13.5 for 1:30 PM)
   * @returns {{ direction: {x: number, y: number, z: number}, elevation: number, azimuth: number, isDaylight: boolean }}
   */
  calculateSunPosition(timeOfDay = 12.0) {
    // Convert 6h - 18h into daylight arc
    const isDaylight = timeOfDay >= 5.5 && timeOfDay <= 18.5;
    
    // Solar elevation angle in radians (0 at horizon, pi/2 at zenith)
    let elevation = 0;
    let azimuth = 0;

    if (isDaylight) {
      const dayProgress = (timeOfDay - 6.0) / 12.0; // 0 at 6:00, 0.5 at 12:00, 1.0 at 18:00
      elevation = Math.sin(dayProgress * Math.PI) * (Math.PI * 0.42); // peak ~ 75 degrees
      azimuth = (dayProgress - 0.5) * Math.PI * 0.9; // sweeps East to West
    } else {
      elevation = -0.2; // below horizon
      azimuth = 0;
    }

    // Direction vector pointing FROM origin TOWARDS the sun
    // In Three.js: Y is up, X is East/West, Z is South/North
    const cosEl = Math.max(0, Math.cos(elevation));
    const x = Math.sin(azimuth) * cosEl;
    const y = Math.sin(elevation);
    const z = Math.cos(azimuth) * cosEl;

    return {
      direction: { x, y, z },
      elevation: Math.max(0, elevation * (180 / Math.PI)), // in degrees
      azimuth: azimuth * (180 / Math.PI),
      isDaylight
    };
  }

  /**
   * Calculates solar irradiance (W/m²) arriving at the earth's surface
   * @param {number} elevationDeg - Sun elevation in degrees
   * @param {number} cloudCover - 0.0 (crystal clear) to 1.0 (heavy overcast)
   * @returns {number} Irradiance in W/m² (0 to ~1050)
   */
  calculateIrradiance(elevationDeg, cloudCover = 0.1) {
    if (elevationDeg <= 0) return 0;

    // Atmospheric air mass model AM = 1 / sin(elevation)
    const sinEl = Math.sin((elevationDeg * Math.PI) / 180);
    // Extraterrestrial constant ~ 1361 W/m²
    const clearSkyDNI = 1050 * Math.pow(sinEl, 1.15);
    const cloudAttenuation = 1.0 - cloudCover * 0.82;

    return Math.max(0, Math.min(1100, clearSkyDNI * cloudAttenuation));
  }

  /**
   * Calculates instantaneous power generated by the solar panel
   * @param {{x: number, y: number, z: number}} panelNormal - Normal vector facing out of panel
   * @param {{x: number, y: number, z: number}} sunDir - Vector pointing towards sun
   * @param {number} irradiance - Current irradiance in W/m²
   * @returns {{ watts: number, efficiencyFactor: number, angleOfIncidenceDeg: number }}
   */
  calculatePanelOutput(panelNormal, sunDir, irradiance) {
    if (irradiance <= 0) {
      return { watts: 0, efficiencyFactor: 0, angleOfIncidenceDeg: 90 };
    }

    // Dot product between normalized vectors
    const lenN = Math.hypot(panelNormal.x, panelNormal.y, panelNormal.z) || 1;
    const lenS = Math.hypot(sunDir.x, sunDir.y, sunDir.z) || 1;

    const nx = panelNormal.x / lenN;
    const ny = panelNormal.y / lenN;
    const nz = panelNormal.z / lenN;

    const sx = sunDir.x / lenS;
    const sy = sunDir.y / lenS;
    const sz = sunDir.z / lenS;

    const dot = nx * sx + ny * sy + nz * sz;
    const cosTheta = Math.max(0, dot); // 0 if facing away from sun
    const angleOfIncidenceRad = Math.acos(Math.min(1, Math.max(0, dot)));
    const angleOfIncidenceDeg = angleOfIncidenceRad * (180 / Math.PI);

    // Efficiency factor (1.0 = optimal perpendicular beam)
    const efficiencyFactor = cosTheta * (irradiance / 1000);
    const watts = this.panelRatedPower * efficiencyFactor;

    return {
      watts: Math.max(0, Math.min(this.panelRatedPower, parseFloat(watts.toFixed(1)))),
      efficiencyFactor: parseFloat(efficiencyFactor.toFixed(3)),
      angleOfIncidenceDeg: parseFloat(angleOfIncidenceDeg.toFixed(1))
    };
  }
}
